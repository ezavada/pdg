'use strict';
// Shared recorder signatures derive from the native semantic-command inventory.
const fs=require('fs'), path=require('path');
const root=path.resolve(__dirname,'..');
const records=()=>JSON.parse(fs.readFileSync(path.join(root,'tools/animation-operations-inventory.json'),'utf8'));
function kind(type) {
    type=type.replace(/\bconst\b|[&*]/g,'').trim();
    if (['double','float','int','uint32','uint32_t','AnimationBoneId','BoneId','BlendMode','FitType','LineStyle'].includes(type)) return 'number';
    if (type==='bool') return 'boolean';
    if (['char','std::string'].includes(type)) return 'string';
    return type==='glm::mat3' ? 'AffineTransform' : type==='AnimatedBase' ? 'Animated' : type;
}
function commands() {return records().filter(r=>r.name!=='diminish').map((r,id)=>({...r,id,params:r.params.map(p=>({...p,kind:kind(p.type)}))}));}
function enrich(api) {
    const all=commands();
    // These are recorder input contracts, not native methods on a live subclass.
    api.animation_commands=all;
    const inherited=new Set(api.interface.find(c=>c.name==='Animated').interface.map(m=>m.name));
    for(const owner of ['AnimationScript','Troupe']) {
        const target=api.interface.find(c=>c.name===owner);
        const names=new Set([...inherited,...target.interface.map(m=>m.name)]);
        for(const name of [...new Set(all.map(r=>r.name))]) {
            if(names.has(name)) continue;
            const variants=[];
            for(const r of all.filter(r=>r.name===name)) {
                const params=r.params.map(p=>{
                    let value={name:p.name,type:['number','boolean','string'].includes(p.kind)?p.kind:'object '+p.kind};
                    if(p.kind==='EasingFunc') value={name:p.name,type:'number',contract:{schema:'EasingFunction'}};
                    if(p.kind==='AffineTransform') value.contract={schema:'AffineTransform'};
                    if(p.kind==='CameraMatchOptions') {
                        const schema=name==='matchFadeTo'?'CameraMatchFadeOptions':'CameraMatchCutOptions';
                        value.type='object '+schema;value.contract={schema};
                    }
                    if(['AnimationPhysicsDriveSettings','ParticleTrailOptions'].includes(p.kind)) value.contract={schema:p.kind};
                    if(p.type.includes('*') && p.kind !== 'string') value.contract={...(value.contract||{type:value.type}),nullable:true};
                    if(p.default) {value.optional=true;value.default_value='undefined';}
                    return value;
                });
                let expanded=[params];
                params.forEach((p,i)=>{if(p.type==='object Color')expanded=expanded.flatMap(v=>[v,v.map((x,j)=>j===i?{...x,type:'string',name:x.name+'Name'}:x),v.map((x,j)=>j===i?{...x,type:'number',name:x.name+'RGBA'}:x)]);});
                for(const v of expanded) if(!variants.some(old=>JSON.stringify(old)===JSON.stringify(v))) variants.push(v);
            }
            target.interface.push({name,type:'function',native:false,brief:'Record '+name+' for compatible playback targets.',params:variants.length===1?variants[0]:variants,returns:'this',returns_contract:{type:'this'}});
        }
    }
    return api;
}
function generate() {
    const all=commands();
    const lines=['// Generated by tools/animation-recorder.js from the native command inventory. Do not edit.','switch (id) {'];
    for(const r of all) {
        lines.push(...r.guards,'case '+r.id+': {');
        const min=r.params.filter(p=>!p.default).length;
        lines.push(`if (count < ${min} || count > ${r.params.length}) throw std::invalid_argument("Invalid recorder argument count");`,'AnimationArguments args;');
        r.params.forEach((p,i)=>lines.push(`if (count > ${i}) args.push_back(read(${i}, "${p.kind}"));`));
        lines.push(`target.recordOperation("${r.name}", std::move(args)); return;`,'}',...r.guards.map(()=> '#endif'));
    }
    lines.push('default: throw std::invalid_argument("Unavailable animation command");','}');
    const file=path.join(root,'src/inc/pdg/sys/animation-recorder-dispatch.inc'),text=lines.join('\n')+'\n';
    if(process.argv.includes('--check')) {if(fs.readFileSync(file,'utf8')!==text)throw Error('Stale recorder dispatch');}
    else fs.writeFileSync(file,text);
}
if(require.main===module)generate();
module.exports={enrich,commands};
